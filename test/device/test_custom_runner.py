def _start_servers(base):
    """Once per `pio test` run, shared by all suites: PlatformIO loads this
    module anew for each suite, and a port closed by one suite is not always
    free again for the next. The threads are daemons and end with the process."""
    servers = getattr(sys, "_arduino4iot_device_test_servers", None)
    if servers is not None:
        return
    tls = ssl.SSLContext(ssl.PROTOCOL_TLS_SERVER)
    tls.load_cert_chain(os.path.join(GENERATED, "server.pem"), os.path.join(GENERATED, "server.key"))
    sys._arduino4iot_device_test_servers = [
        _Server(base),
        _Server(base + 1, ssl_context=tls),
        _Server(base + 2, stall=True),
        # base + 3 stays closed: the connect is refused (or dropped by a firewall)
    ]


class CustomTestRunner(UnityTestRunner):

    def setup(self):
        build_dir = self.project_config.get("platformio", "build_dir")
        sys._arduino4iot_device_test_firmware = os.path.join(
            build_dir, self.test_suite.env_name, "firmware.bin")
        host = os.environ.get("DEVICE_TEST_HOST") or _default_host()
        base = int(os.environ.get("DEVICE_TEST_PORT_BASE", "18080"))
        os.makedirs(GENERATED, exist_ok=True)
        _make_certificates(host)
        _write_header(host, base,
                      os.environ.get("DEVICE_TEST_WIFI_SSID", ""),
                      os.environ.get("DEVICE_TEST_WIFI_PASSWORD", ""))
        _start_servers(base)
        print(f"Device test server on {host}:{base}..{base + 2}")
