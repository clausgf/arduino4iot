"""
On-device tests of arduino4iot: the Unity runner, plus a test server on the
host that the device talks to over WiFi.

PlatformIO picks this file up for every suite below test/device/ because the
`device` environment sets `test_framework = custom` (see platformio.ini).
Before building, setup() generates test/device/generated/device_test_env.h
(host address, ports, test CA certificates) and starts the servers, which run
until `pio test` ends. Nothing here runs in CI: CI only runs `pio test -e native`.

Environment variables (all optional):
  DEVICE_TEST_HOST       address the device reaches the host at
                         (default: the address of the host's default route)
  DEVICE_TEST_PORT_BASE  first of four TCP ports (default 18080)
  DEVICE_TEST_WIFI_SSID / DEVICE_TEST_WIFI_PASSWORD
                         WiFi credentials; default: the ones seeded into the
                         device's NVS (namespace "iot"), so none are needed
                         on a provisioned device
"""

import os
import socket
import ssl
import subprocess
import sys
import threading
import time

from platformio.test.runners.unity import UnityTestRunner

HERE = os.path.dirname(os.path.abspath(__file__))
GENERATED = os.path.join(HERE, "generated")


def _default_host():
    probe = socket.socket(socket.AF_INET, socket.SOCK_DGRAM)
    try:
        probe.connect(("192.0.2.1", 9))  # TEST-NET-1: nothing is sent
        return probe.getsockname()[0]
    finally:
        probe.close()


# *****************************************************************************
# Certificates
# *****************************************************************************

def _openssl(*args):
    subprocess.run(["openssl", *args], check=True, cwd=GENERATED,
                   stdout=subprocess.DEVNULL, stderr=subprocess.DEVNULL)


def _make_certificates(host):
    """A test CA, a server certificate for @p host signed by it, and an
    unrelated CA for the "wrong CA" case. EC P-256: quick on the ESP32."""
    marker = os.path.join(GENERATED, "server.host")
    if os.path.exists(marker) and open(marker).read() == host:
        return
    for name in ("ca", "other_ca"):
        _openssl("req", "-x509", "-newkey", "ec", "-pkeyopt", "ec_paramgen_curve:P-256",
                 "-nodes", "-keyout", f"{name}.key", "-out", f"{name}.pem", "-days", "3650",
                 "-subj", f"/CN=arduino4iot device test {name}")
    _openssl("req", "-newkey", "ec", "-pkeyopt", "ec_paramgen_curve:P-256", "-nodes",
             "-keyout", "server.key", "-out", "server.csr", "-subj", f"/CN={host}")
    with open(os.path.join(GENERATED, "server.ext"), "w") as ext:
        ext.write(f"subjectAltName=IP:{host}\nbasicConstraints=CA:FALSE\n")
    _openssl("x509", "-req", "-in", "server.csr", "-CA", "ca.pem", "-CAkey", "ca.key",
             "-CAcreateserial", "-out", "server.pem", "-days", "3650", "-extfile", "server.ext")
    with open(marker, "w") as out:
        out.write(host)


def _c_string(text):
    return '"' + text.replace("\\", "\\\\").replace('"', '\\"').replace("\n", "\\n") + '"'


def _write_header(host, base, ssid, password):
    def pem(name):
        with open(os.path.join(GENERATED, name)) as f:
            return f.read()
    lines = [
        "// Generated by test/device/test_custom_runner.py - do not edit, not in git.",
        "#pragma once",
        f"#define DEVICE_TEST_HOST {_c_string(host)}",
        f"#define DEVICE_TEST_HTTP_PORT {base}",
        f"#define DEVICE_TEST_HTTPS_PORT {base + 1}",
        f"#define DEVICE_TEST_STALL_PORT {base + 2}",
        f"#define DEVICE_TEST_CLOSED_PORT {base + 3}",
        f"#define DEVICE_TEST_WIFI_SSID {_c_string(ssid)}",
        f"#define DEVICE_TEST_WIFI_PASSWORD {_c_string(password)}",
        f"static const char DEVICE_TEST_CA_PEM[] = {_c_string(pem('ca.pem'))};",
        f"static const char DEVICE_TEST_OTHER_CA_PEM[] = {_c_string(pem('other_ca.pem'))};",
        "",
    ]
    path = os.path.join(GENERATED, "device_test_env.h")
    content = "\n".join(lines)
    # unchanged content keeps the file's time stamp, so nothing rebuilds
    if not os.path.exists(path) or open(path).read() != content:
        with open(path, "w") as out:
            out.write(content)


# *****************************************************************************
# Test server
# *****************************************************************************

class _Connection:
    """One client connection: a minimal, deliberately controllable HTTP/1.1
    server, so the tests can produce what a real server rarely does."""

    _next_id = 0
    _lock = threading.Lock()

    def __init__(self, sock):
        self.sock = sock
        self.buffer = b""
        with _Connection._lock:
            _Connection._next_id += 1
            self.id = _Connection._next_id
        self.drop_next = False

    def _read_request(self):
        while b"\r\n\r\n" not in self.buffer:
            data = self.sock.recv(4096)
            if not data:
                return None
            self.buffer += data
        head, self.buffer = self.buffer.split(b"\r\n\r\n", 1)
        lines = head.decode("latin-1").split("\r\n")
        method, target, _ = lines[0].split(" ", 2)
        headers = {}
        for line in lines[1:]:
            name, value = line.split(":", 1)
            headers[name.strip().lower()] = value.strip()
        length = int(headers.get("content-length", "0"))
        while len(self.buffer) < length:
            data = self.sock.recv(65536)
            if not data:
                return None
            self.buffer += data
        body, self.buffer = self.buffer[:length], self.buffer[length:]
        return method, target, headers, body

    def _send(self, data):
        """In pieces: the socket timeout bounds one sendall() as a whole, and a
        large body over a weak link can take longer than that."""
        for i in range(0, len(data), 8192):
            self.sock.sendall(data[i:i + 8192])

    def _respond(self, status, body=b"", headers=None, head_only=False):
        reason = {200: "OK", 204: "No Content", 304: "Not Modified", 404: "Not Found"}.get(status, "X")
        out = [f"HTTP/1.1 {status} {reason}", f"X-Conn: {self.id}"]
        if status not in (204, 304):
            out.append(f"Content-Length: {len(body)}")
        for name, value in (headers or {}).items():
            out.append(f"{name}: {value}")
        data = ("\r\n".join(out) + "\r\n\r\n").encode()
        if not head_only and status not in (204, 304):
            data += body
        self._send(data)

    @staticmethod
    def _pattern(n):
        return bytes(i % 251 for i in range(n))

    def serve(self):
        while True:
            request = self._read_request()
            if request is None:
                return
            if self.drop_next:
                return  # close without an answer, as an idle-timeout race would
            method, target, headers, body = request
            parts = target.strip("/").split("/")
            route = parts[0]
            args = [int(p) for p in parts[1:] if p.isdigit()]
            head_only = method == "HEAD"

            if route == "hello":
                self._respond(200, b"hello", {"ETag": '"e1"', "Last-Modified": "Tue, 10 Nov 2026 08:00:00 GMT"},
                              head_only)
            elif route == "bytes":
                self._respond(200, self._pattern(args[0]))
            elif route == "chunked":
                n, size = args[0], 1000
                data = self._pattern(n)
                self.sock.sendall(f"HTTP/1.1 200 OK\r\nX-Conn: {self.id}\r\n"
                                  "Transfer-Encoding: chunked\r\n\r\n".encode())
                for i in range(0, n, size):
                    piece = data[i:i + size]
                    self.sock.sendall(f"{len(piece):x}\r\n".encode() + piece + b"\r\n")
                self.sock.sendall(b"0\r\n\r\n")
            elif route == "close":
                self.sock.sendall(b"HTTP/1.0 200 OK\r\n\r\n" + self._pattern(args[0]))
                return
            elif route == "status":
                self._respond(args[0], b"x")
            elif route == "echo":
                checksum = sum(body) & 0xFFFFFFFF
                self._respond(200, f"{len(body)}:{checksum}".encode(),
                              {"X-Echo": headers.get("x-test", "")})
            elif route == "drop-next":
                self._respond(200, b"armed")
                self.drop_next = True
            elif route == "trickle-body":
                n, pause_ms = args
                self.sock.sendall(f"HTTP/1.1 200 OK\r\nContent-Length: {n}\r\n\r\n".encode())
                for _ in range(n):
                    time.sleep(pause_ms / 1000)
                    self.sock.sendall(b"x")
            elif route == "trickle-head":
                pause_ms = args[0]
                for i in range(100):
                    self.sock.sendall(f"HTTP/1.1 200 OK\r\n" .encode() if i == 0
                                      else f"X-Slow-{i}: 1\r\n".encode())
                    time.sleep(pause_ms / 1000)
                return
            elif route == "stall":
                self.sock.sendall(b"HTTP/1.1 200 OK\r\nContent-Length: 10\r\n\r\nab")
                time.sleep(30)
                return
            elif route == "progress":
                # n bytes in 1 KB pieces, one every pause_ms: slow, but progressing
                n, pause_ms = args
                self.sock.sendall(f"HTTP/1.1 200 OK\r\nContent-Length: {n}\r\n\r\n".encode())
                data = self._pattern(n)
                for i in range(0, n, 1024):
                    time.sleep(pause_ms / 1000)
                    self.sock.sendall(data[i:i + 1024])
            elif route == "malformed":
                self.sock.sendall(b"HTX/1.1 200 OK\r\n\r\n")
                return
            elif route == "firmware":
                # the image of the suite under test, as the OTA source
                with open(sys._arduino4iot_device_test_firmware, "rb") as f:
                    image = f.read()
                variant = parts[1] if len(parts) > 1 else ""
                # 64 KB of it are enough to fail, and quick over a weak link
                if variant == "truncated":
                    # complete as far as HTTP goes, but not a valid image
                    self._respond(200, image[:65536])
                elif variant == "cut":
                    # the connection ends long before the announced length
                    self._send(f"HTTP/1.1 200 OK\r\nContent-Length: {len(image)}\r\n\r\n".encode()
                               + image[:65536])
                    return
                else:
                    self._respond(200, image, {"ETag": '"fw1"', "Last-Modified": "Tue, 10 Nov 2026 08:00:00 GMT"})
            else:
                self._respond(404, b"not found")


class _Server:
    def __init__(self, port, ssl_context=None, stall=False):
        self.ssl_context = ssl_context
        self.stall = stall
        self.listener = socket.socket(socket.AF_INET, socket.SOCK_STREAM)
        self.listener.setsockopt(socket.SOL_SOCKET, socket.SO_REUSEADDR, 1)
        self.listener.bind(("0.0.0.0", port))
        self.listener.listen(16)
        self.listener.settimeout(0.5)
        self.running = True
        self.thread = threading.Thread(target=self._accept, daemon=True)
        self.thread.start()

    def _accept(self):
        while self.running:
            try:
                sock, _ = self.listener.accept()
            except socket.timeout:
                continue
            except OSError:
                return
            threading.Thread(target=self._handle, args=(sock,), daemon=True).start()

    def _handle(self, sock):
        sock.settimeout(60)
        try:
            if self.stall:
                time.sleep(30)  # accepts TCP, never answers the TLS handshake
                return
            if self.ssl_context is not None:
                sock = self.ssl_context.wrap_socket(sock, server_side=True)
            _Connection(sock).serve()
        except (OSError, ssl.SSLError, ValueError):
            pass
        finally:
            try:
                sock.close()
            except OSError:
                pass

    def stop(self):
        self.running = False
        self.listener.close()


